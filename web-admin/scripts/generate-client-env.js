#!/usr/bin/env node

/**
 * Generate client-side environment config from .env
 * This script reads CONFIG_* variables and generates a TypeScript file
 * that can be imported by client-side code.
 *
 * This is needed because Turbopack only exposes NEXT_PUBLIC_* variables
 * directly from .env file, and doesn't process next.config.ts env property.
 */

const fs = require('fs');
const path = require('path');

// Load .env file
const envPath = path.join(__dirname, '..', '.env');
const envVars = {};

if (fs.existsSync(envPath)) {
  const envContent = fs.readFileSync(envPath, 'utf-8');
  envContent.split('\n').forEach(line => {
    const trimmed = line.trim();
    if (trimmed && !trimmed.startsWith('#')) {
      const [key, ...valueParts] = trimmed.split('=');
      const value = valueParts.join('=');
      if (key && value !== undefined) {
        envVars[key.trim()] = value.trim();
      }
    }
  });
}

// Extract the values we need for client-side
const clientEnv = {
  GATEWAY_URL: envVars.CONFIG_API_GATEWAY_URL || '',
  RESOURCE_URL: envVars.CONFIG_RESOURCE_URL || '',
  SERVICE_IDS: {
    API_ADMIN: envVars.CONFIG_NODEJS_ADMIN_SERVICE_ID || '',
    API_DASHBOARD: envVars.CONFIG_NODEJS_MANAGEMENT_SERVICE_ID || '',
    API_UPLOAD: envVars.CONFIG_NODEJS_MEDIA_SERVICE_ID || '',
    API_OAUTH: envVars.CONFIG_NODEJS_OAUTH_SERVICE_ID || '',
    API_APP_FOOD: envVars.CONFIG_NODEJS_APP_FOOD_SERVICE_ID || '',
  }
};

// Generate TypeScript file
const outputPath = path.join(__dirname, '..', 'src', 'config', 'client-env.ts');

// Ensure config directory exists
const configDir = path.dirname(outputPath);
if (!fs.existsSync(configDir)) {
  fs.mkdirSync(configDir, { recursive: true });
}

const content = `// AUTO-GENERATED FILE - DO NOT EDIT
// Generated by scripts/generate-client-env.js from .env
// Run "npm run generate:env" to regenerate

export const CLIENT_ENV = {
  GATEWAY_URL: "${clientEnv.GATEWAY_URL}",
  RESOURCE_URL: "${clientEnv.RESOURCE_URL}",
  SERVICE_IDS: {
    API_ADMIN: "${clientEnv.SERVICE_IDS.API_ADMIN}",
    API_DASHBOARD: "${clientEnv.SERVICE_IDS.API_DASHBOARD}",
    API_UPLOAD: "${clientEnv.SERVICE_IDS.API_UPLOAD}",
    API_OAUTH: "${clientEnv.SERVICE_IDS.API_OAUTH}",
    API_APP_FOOD: "${clientEnv.SERVICE_IDS.API_APP_FOOD}",
  }
} as const;

export const GATEWAY_URL = CLIENT_ENV.GATEWAY_URL;
export const RESOURCE_URL = CLIENT_ENV.RESOURCE_URL;
export const SERVICE_IDS = CLIENT_ENV.SERVICE_IDS;
`;

fs.writeFileSync(outputPath, content, 'utf-8');

console.log('[generate-client-env] Generated client environment config:');
console.log('  Output:', outputPath);
console.log('  GATEWAY_URL:', clientEnv.GATEWAY_URL || '(empty)');
console.log('  SERVICE_IDS:', JSON.stringify(clientEnv.SERVICE_IDS));
